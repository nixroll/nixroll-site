/**
 * ТЗ 3: типографика. Русский текст — неразрывные пробелы после однобуквенных
 * предлогов/союзов, между числом и единицей измерения, внутри групп разрядов,
 * перед частицами же/ли/бы и перед тире. Латинские кавычки/апострофы и
 * длинное тире в тексте не используются (только дефис с пробелами для
 * диапазонов лет — это уже так в исходном контенте).
 *
 * Применяется только к русскому контенту при рендере; английский текст
 * не обрабатывается.
 */

const ONE_LETTER_WORDS =
  "[авикосуявo]|[АВИКОСУЯВO]|же|ли|бы|Же|Ли|Бы";

const NBSP = " ";

export function applyRuTypography(input: string): string {
  let text = input;

  // Однобуквенные предлоги/союзы + следующее слово.
  text = text.replace(
    new RegExp(`(^|[\\s(])(${ONE_LETTER_WORDS})\\s+`, "g"),
    (_match, pre: string, word: string) => `${pre}${word}${NBSP}`
  );

  // Частицы «же», «ли», «бы» — неразрывный пробел перед частицей.
  text = text.replace(/\s+(же|ли|бы)(?=[\s.,!?;:]|$)/g, `${NBSP}$1`);

  // Число + пробел + единица измерения / знак (ГБ, ТБ/с, %, ₽ и т.п.).
  text = text.replace(
    /(\d)\s+([%№§]|[A-Za-zА-Яа-яЁё]{1,4}(?:\/[A-Za-zА-Яа-яЁё]+)?\b)/g,
    (_m, digit: string, unit: string) => `${digit}${NBSP}${unit}`
  );

  // Пробел перед тире/дефисом-разделителем (не внутри слова).
  text = text.replace(/\s+-\s+/g, `${NBSP}- `);

  return text;
}

/**
 * Применяет типографику построчно к массиву абзацев (тело заметок и т.п.).
 */
export function applyRuTypographyToParagraphs(paragraphs: string[]): string[] {
  return paragraphs.map(applyRuTypography);
}
