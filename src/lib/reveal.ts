/**
 * Порядковый номер в очереди появления (в шагах `--stagger`).
 *
 * По умолчанию номер берётся из положения в разметке, но переключатель
 * языка должен идти последним — на шаг позже самого позднего элемента
 * страницы. Насколько поздний этот элемент, зависит от состава страницы
 * (шесть строк контактов, шесть мест работы по три части и так далее),
 * поэтому номер считает сама страница и передаёт его компоненту.
 *
 * Считать по факту в браузере нельзя: к моменту, когда отработает
 * скрипт, анимация уже началась, и первый показ страницы был бы неверным.
 */
export function slotAfter(...tails: number[]): number {
  return Math.max(0, ...tails) + 1;
}
